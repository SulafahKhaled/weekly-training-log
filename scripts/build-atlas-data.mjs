// Extracts the Muscle Atlas 3D artifact's data (MUSCLES, ALIAS, DAYS, RAW_EXERCISES) into
// src/data/atlas.generated.js so the exercise/muscle library reuses it verbatim instead of
// being retyped. Only the plain-data literals are evaluated (in an empty vm context) — none
// of the artifact's rendering code is run.
//
//   node scripts/build-atlas-data.mjs [path/to/muscle-atlas.html]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcPath = process.argv[2] || path.join(here, 'source', 'muscle-atlas.html');
const outPath = path.join(here, '..', 'src', 'data', 'atlas.generated.js');
const html = fs.readFileSync(srcPath, 'utf8');
const lines = html.split('\n');

// Slice from the first line starting with `startPrefix` through the line that closes the literal.
function sliceBlock(startPrefix, endPredicate) {
  const start = lines.findIndex((l) => l.startsWith(startPrefix));
  if (start < 0) throw new Error(`Atlas source: could not find "${startPrefix}"`);
  for (let i = start; i < lines.length; i++) {
    if (endPredicate(lines[i], i, start)) return lines.slice(start, i + 1).join('\n');
  }
  throw new Error(`Atlas source: unterminated block for "${startPrefix}"`);
}

const musclesSrc = sliceBlock('const MUSCLES = {', (l) => l.trim() === '};');
const aliasSrc = sliceBlock('const ALIAS =', (l) => l.trim().endsWith('};'));
const daysSrc = sliceBlock('const DAYS = [', (l) => l.trim() === '];');
const groupsSrc = sliceBlock('const MOBILITY_GROUPS =', (l) => l.trim().endsWith(';'));
const rawSrc = sliceBlock('const RAW_EXERCISES = [', (l) => l.trim() === '];');
const helperSrc = sliceBlock('const X = (', (l) => l.trim().startsWith('const X = ('));
const pushSrc = sliceBlock('RAW_EXERCISES.push(', (l) => l.trim() === ');');

const ctx = vm.createContext({});
vm.runInContext(
  [musclesSrc, aliasSrc, daysSrc, groupsSrc, rawSrc, helperSrc, pushSrc].join('\n') +
    '\nglobalThis.__out = { MUSCLES, ALIAS, DAYS, MOBILITY_GROUPS, RAW_EXERCISES };',
  ctx
);
const { MUSCLES, ALIAS, DAYS, MOBILITY_GROUPS, RAW_EXERCISES } = ctx.__out;

const decode = (s) => s.replace(/&mdash;/g, '—').replace(/&amp;/g, '&');
const norm = (k) => ALIAS[k] || k;
const uniq = (arr) => Array.from(new Set(arr.map(norm)));

const muscles = {};
for (const [key, m] of Object.entries(MUSCLES)) {
  muscles[key] = { label: m.label, ...(m.note ? { note: m.note } : {}) };
}

const groups = DAYS.map((d) => ({ key: d.key, en: decode(d.en), ar: d.ar, short: d.short || null }));

const exercises = RAW_EXERCISES.map((e) => {
  const primary = uniq(e.primary);
  const secondary = uniq(e.secondary).filter((k) => !primary.includes(k));
  for (const k of [...primary, ...secondary]) {
    if (!muscles[k]) throw new Error(`Atlas exercise "${e.id}" uses unknown muscle key "${k}"`);
  }
  return { id: e.id, name: e.name, groups: e.days, primary, secondary, direction: e.direction };
});

const header = `// GENERATED by scripts/build-atlas-data.mjs from scripts/source/muscle-atlas.html — do not edit by hand.
// Source: "Muscle Atlas 3D" artifact (MUSCLES map + RAW_EXERCISES list). Muscle keys are the Atlas's own;
// the Atlas's legacy aliases (antDelt, midTrap, ...) are already collapsed onto the real keys here.
`;
const body = [
  `export const ATLAS_MUSCLES = ${JSON.stringify(muscles, null, 2)};`,
  `export const ATLAS_GROUPS = ${JSON.stringify(groups, null, 2)};`,
  `export const ATLAS_MOBILITY_GROUPS = ${JSON.stringify(MOBILITY_GROUPS)};`,
  `export const ATLAS_EXERCISES = ${JSON.stringify(exercises, null, 2)};`,
].join('\n\n');

fs.writeFileSync(outPath, `${header}\n${body}\n`);
console.log(`Wrote ${path.relative(process.cwd(), outPath)}: ${Object.keys(muscles).length} muscles, ${groups.length} groups, ${exercises.length} exercises`);
