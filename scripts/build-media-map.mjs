// Turns exercise-media-map.md (the user's verified YouTube mapping) into src/data/mediaMap.generated.js.
// Only the file's own "JSON for the app" block + its table notes are used — nothing is invented.
//   node scripts/build-media-map.mjs [exercise-media-map.md]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcPath = path.resolve(process.argv[2] || path.join(root, 'exercise-media-map.md'));
const text = fs.readFileSync(srcPath, 'utf8');
const verified = fs.statSync(srcPath).mtime.toISOString().slice(0, 10);

const block = text.slice(text.indexOf('## JSON for the app')).match(/```json\n([\s\S]*?)\n```/);
if (!block) throw new Error('No "JSON for the app" block found');
const json = JSON.parse(block[1]);

// table notes: | `id` | name | day | `video` | channel | title | notes |
const notes = {};
for (const line of text.split('\n')) {
  const m = line.match(/^\|\s*`([^`]+)`\s*\|(?:[^|]*\|){5}\s*([^|]*?)\s*\|\s*$/);
  if (m && m[2]) notes[m[1]] = m[2];
}

// Entries the file keys under a name the library spells differently, or that are a 2nd video for the same exercise.
const ALIAS = { breath_9090: 'breath_90_90_wall', breath_legs_up: 'legs_up_wall' };
// PDF yoga sections that are exactly ONE pose reuse that pose's video (composite sections get none).
const SECTION_FROM_POSE = { yoga_2: 'sun_salutation', yoga_4: 'lizard_pyramid', yoga_5: 'pigeon', yoga_6: 'bound_angle' };
const ALSO = { lizard_pyramid: 'lizard_pyramid_b', bound_angle: 'bound_angle_b', breath_legs_up: 'breath_4_8_sleep' };

const out = {};
const entry = (id, key, extraNote) => {
  const v = json[key];
  if (!v) return;
  const parts = [notes[key], extraNote].filter(Boolean);
  const also = ALSO[id] && json[ALSO[id]] ? `Also: https://www.youtube.com/watch?v=${json[ALSO[id]].youtube} (${json[ALSO[id]].title}, ${json[ALSO[id]].channel})` : null;
  if (also) parts.push(also);
  out[id] = { url: `https://www.youtube.com/watch?v=${v.youtube}`, start: null, source: v.channel, title: v.title, verified, note: parts.join(' · ') || null };
};
for (const key of Object.keys(json)) if (!/_b$/.test(key) && !['legs_up_wall', 'breath_4_8_sleep', 'breath_90_90_wall'].includes(key)) entry(key, key);
for (const [id, key] of Object.entries(ALIAS)) entry(id, key);
for (const [id, pose] of Object.entries(SECTION_FROM_POSE)) entry(id, pose, 'Video of the pose this section is made of.');

const header = `// GENERATED by scripts/build-media-map.mjs from exercise-media-map.md — do not edit by hand.
// Every link was checked through YouTube oEmbed (exists + embeddable) by whoever produced the mapping;
// the videos themselves were not watched, so form quality is judged by title/channel only.
`;
fs.writeFileSync(path.join(root, 'src', 'data', 'mediaMap.generated.js'), `${header}export const MEDIA_MAP = ${JSON.stringify(out, null, 2)};\n`);
console.log(`mediaMap.generated.js: ${Object.keys(out).length} exercises mapped (verified ${verified})`);
